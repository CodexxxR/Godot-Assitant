const createFallbackManifest = ({ prompt, assets }) => {
  const projectName = sanitizeProjectName(slugProjectName(prompt));
  const assetPaths = assets.map((asset) => asset.destinationPath).filter(Boolean);
  const mainScene = "scenes/Main.tscn";

  return {
    projectName,
    summary: "Generated fallback Godot shooter prototype.",
    mainScene,
    files: fallbackFiles({ projectName, mainScene, prompt, assetPaths }),
    notes: [
      "The AI response could not be parsed as a project manifest, so Godot Assistant generated a runnable fallback prototype.",
    ],
  };
};

const buildManifestPrompt = ({ prompt, assets }) => {
  const assetList = assets.length
    ? assets
        .map(
          (asset) =>
            `- ${asset.name} (${asset.extension || "asset"}, ${asset.size || 0} bytes) -> res://${asset.destinationPath}`
        )
        .join("\n")
    : "- No user assets were provided. Build a complete prototype with code-drawn placeholders.";

  return `
You are a senior Godot 4 engineer generating complete importable Godot projects.

Return ONLY valid JSON. No Markdown. No commentary.

Required JSON shape:
{
  "projectName": "Short Game Name",
  "summary": "One sentence summary",
  "mainScene": "scenes/Main.tscn",
  "files": [
    { "path": "project.godot", "content": "complete file contents" },
    { "path": "scenes/Main.tscn", "content": "complete file contents" },
    { "path": "scripts/Main.gd", "content": "complete file contents" }
  ],
  "notes": ["short implementation note"]
}

Rules:
- Generate a small but complete Godot 4.x project that can be opened by importing the generated folder in Godot.
- Include project.godot, one main .tscn scene, and all scripts needed to run.
- Prefer GDScript and code-created gameplay objects over fragile scene dependencies.
- Use typed GDScript where natural.
- Use the provided assets by referencing their res:// paths when useful. Do not embed binary data or base64.
- File paths must be relative and use only project.godot, scenes/, scripts/, resources/, data/, or README.md.
- Keep the project focused enough for free OpenRouter models: at most 12 files, each complete.
- Avoid placeholders like "TODO" or "implement later".
- The result must be playable with keyboard/mouse immediately.

User project request:
${prompt}

Available copied assets:
${assetList}
`;
};

const normalizeManifest = ({ manifest, prompt, assets }) => {
  const projectName = sanitizeProjectName(manifest.projectName || slugProjectName(prompt));
  const mainScene = normalizePath(manifest.mainScene || "scenes/Main.tscn");
  const seen = new Set();
  const files = [];

  (Array.isArray(manifest.files) ? manifest.files : []).forEach((file) => {
    const filePath = normalizePath(file?.path || "");
    if (!isValidGeneratedFilePath(filePath) || seen.has(filePath)) return;
    if (typeof file?.content !== "string") return;

    seen.add(filePath);
    files.push({
      path: filePath,
      content: file.content.replace(/\r\n/g, "\n"),
    });
  });

  const upsertFile = (path, content) => {
    const index = files.findIndex((file) => file.path === path);
    if (index === -1) {
      files.unshift({ path, content });
    } else {
      files[index] = { path, content };
    }
  };

  upsertFile("project.godot", makeProjectGodot({ projectName, mainScene }));

  if (!files.some((file) => file.path === mainScene)) {
    files.push({ path: mainScene, content: makeMainScene() });
  }

  if (!files.some((file) => file.path === "scripts/Main.gd")) {
    files.push({
      path: "scripts/Main.gd",
      content: makeMainScript({
        prompt,
        assetPaths: assets.map((asset) => asset.destinationPath).filter(Boolean),
      }),
    });
  }

  return {
    projectName,
    summary: String(manifest.summary || "Generated Godot project."),
    mainScene,
    files: files.slice(0, 16),
    notes: Array.isArray(manifest.notes) ? manifest.notes.map(String).slice(0, 8) : [],
  };
};

const generateProjectManifest = async ({ prompt, assets = [] }) => {
  const validPrompt = requireString(prompt, "prompt");
  const normalizedAssets = Array.isArray(assets)
    ? assets
        .map((asset) => ({
          name: String(asset?.name || "").trim(),
          extension: String(asset?.extension || "").trim(),
          size: Number(asset?.size || 0),
          destinationPath: normalizePath(asset?.destinationPath || ""),
        }))
        .filter((asset) => asset.name && asset.destinationPath)
        .slice(0, 40)
    : [];

  let output = "";
  let model = "";

  try {
    const result = await streamGenerate({
      prompt: buildManifestPrompt({
        prompt: validPrompt,
        assets: normalizedAssets,
      }),
      system:
        "You output strict JSON manifests for complete Godot projects. You never output Markdown.",
      onToken: (token) => {
        output += token;
      },
    });

    model = result?.model || "";
    const manifest = parseManifest(output);

    return {
      ...normalizeManifest({
        manifest,
        prompt: validPrompt,
        assets: normalizedAssets,
      }),
      model,
      usedFallback: false,
    };
  } catch (error) {
    if (!output.trim()) {
      throw error;
    }

    logger.warn("Falling back to generated Godot project template", {
      message: error instanceof Error ? error.message : String(error),
      outputPreview: output.slice(0, 240),
    });

    return {
      ...createFallbackManifest({
        prompt: validPrompt,
        assets: normalizedAssets,
      }),
      model,
      usedFallback: true,
    };
  }
};

