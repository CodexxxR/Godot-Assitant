const TEXT_FILE_EXTENSIONS = new Set([
  ".gd",
  ".gdshader",
  ".shader",
  ".tscn",
  ".tres",
  ".godot",
  ".cfg",
  ".ini",
  ".import",
  ".gdextension",
  ".json",
  ".md",
  ".txt",
  ".yml",
  ".yaml",
  ".cs",
]);

const normalizePath = (filePath = "") =>
  String(filePath).replace(/\\/g, "/").replace(/^\/+/, "");

const getExtension = (filePath = "") => {
  const normalized = normalizePath(filePath).toLowerCase();
  const index = normalized.lastIndexOf(".");
  return index === -1 ? "" : normalized.slice(index);
};

const sanitizeProjectName = (name = "") => {
  const cleaned = String(name)
    .replace(/[^a-zA-Z0-9 _-]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

  return cleaned || "Generated Godot Project";
};

const slugProjectName = (prompt = "") => {
  const words = String(prompt)
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, " ")
    .split(/\s+/)
    .filter((word) => word && !["build", "make", "create", "a", "an", "the", "game"].includes(word))
    .slice(0, 4);

  if (!words.length) return "Generated Godot Project";
  return words.map((word) => word[0].toUpperCase() + word.slice(1)).join(" ");
};

const toJsonText = (raw = "") => {
  const fence = raw.match(/```(?:json)?\s*([\s\S]*?)```/i);
  const candidate = (fence ? fence[1] : raw).trim();
  const firstBrace = candidate.indexOf("{");
  const lastBrace = candidate.lastIndexOf("}");

  if (firstBrace === -1 || lastBrace === -1 || lastBrace <= firstBrace) {
    return candidate;
  }

  return candidate.slice(firstBrace, lastBrace + 1);
};

const parseManifest = (raw = "") => JSON.parse(toJsonText(raw));

const isValidGeneratedFilePath = (filePath = "") => {
  const normalized = normalizePath(filePath);
  if (!normalized || normalized.startsWith(".") || normalized.includes("../")) return false;
  return TEXT_FILE_EXTENSIONS.has(getExtension(normalized));
};

const makeProjectGodot = ({ projectName, mainScene }) => `; Engine configuration file.
; Generated by Godot Assistant.
config_version=5

[application]

config/name="${projectName.replace(/"/g, "'")}"
run/main_scene="res://${mainScene}"
config/features=PackedStringArray("4.2")

[rendering]

renderer/rendering_method="gl_compatibility"
`;

const makeMainScene = () => `[gd_scene load_steps=2 format=3]

[ext_resource type="Script" path="res://scripts/Main.gd" id="1_main"]

[node name="Main" type="Node2D"]
script = ExtResource("1_main")
`;

const makeMainScript = ({ prompt, assetPaths }) => {
  const assets = JSON.stringify(assetPaths, null, 2);
  return `extends Node2D

const PlayerScript := preload("res://scripts/Player.gd")
const ProjectileScript := preload("res://scripts/Projectile.gd")
const EnemyScript := preload("res://scripts/Enemy.gd")
const IMPORTED_ASSETS := ${assets}

var player: Node2D
var projectiles: Array[Node2D] = []
var enemies: Array[Node2D] = []
var score := 0
var spawn_timer := 0.0
var banner: Label

func _ready() -> void:
\trandomize()
\tbanner = Label.new()
\tbanner.position = Vector2(18, 14)
\tbanner.text = "Generated prototype: ${prompt.replace(/"/g, "'").slice(0, 90)}\\nMove WASD/Arrows. Shoot with mouse or Space."
\tadd_child(banner)
\tplayer = PlayerScript.new()
\tplayer.position = get_viewport_rect().size * 0.5
\tplayer.shoot_requested.connect(_on_player_shoot_requested)
\tadd_child(player)
\tfor index in range(5):
\t\t_spawn_enemy()
\t_create_asset_preview()

func _process(delta: float) -> void:
\tspawn_timer -= delta
\tif spawn_timer <= 0.0:
\t\tspawn_timer = max(0.35, 1.4 - float(score) * 0.02)
\t\t_spawn_enemy()
\t_update_projectiles(delta)
\t_update_enemies(delta)
\tbanner.text = "Score: %s\\nMove WASD/Arrows. Shoot with mouse or Space." % score

func _on_player_shoot_requested(origin: Vector2, direction: Vector2) -> void:
\tvar projectile := ProjectileScript.new()
\tprojectile.position = origin
\tprojectile.direction = direction.normalized()
\tprojectiles.append(projectile)
\tadd_child(projectile)

func _spawn_enemy() -> void:
\tvar viewport_size := get_viewport_rect().size
\tvar enemy := EnemyScript.new()
\tvar side := randi() % 4
\tif side == 0:
\t\tenemy.position = Vector2(randf_range(0.0, viewport_size.x), -40.0)
\telif side == 1:
\t\tenemy.position = Vector2(viewport_size.x + 40.0, randf_range(0.0, viewport_size.y))
\telif side == 2:
\t\tenemy.position = Vector2(randf_range(0.0, viewport_size.x), viewport_size.y + 40.0)
\telse:
\t\tenemy.position = Vector2(-40.0, randf_range(0.0, viewport_size.y))
\tenemies.append(enemy)
\tadd_child(enemy)

func _update_projectiles(delta: float) -> void:
\tvar viewport := Rect2(Vector2.ZERO, get_viewport_rect().size).grow(120.0)
\tfor projectile in projectiles.duplicate():
\t\tprojectile.tick(delta)
\t\tif not viewport.has_point(projectile.position):
\t\t\tprojectiles.erase(projectile)
\t\t\tprojectile.queue_free()

func _update_enemies(delta: float) -> void:
\tfor enemy in enemies.duplicate():
\t\tenemy.tick(delta, player.position)
\t\tif enemy.position.distance_to(player.position) < enemy.radius + 18.0:
\t\t\tscore = max(0, score - 1)
\t\t\tenemies.erase(enemy)
\t\t\tenemy.queue_free()
\t\t\tcontinue
\t\tfor projectile in projectiles.duplicate():
\t\t\tif enemy.position.distance_to(projectile.position) < enemy.radius + projectile.radius:
\t\t\t\tscore += 1
\t\t\t\tenemies.erase(enemy)
\t\t\t\tprojectiles.erase(projectile)
\t\t\t\tenemy.queue_free()
\t\t\t\tprojectile.queue_free()
\t\t\t\tbreak

func _create_asset_preview() -> void:
\tvar x := 18.0
\tfor asset_path in IMPORTED_ASSETS:
\t\tvar texture := load(asset_path)
\t\tif texture is Texture2D:
\t\t\tvar sprite := Sprite2D.new()
\t\t\tsprite.texture = texture
\t\t\tsprite.position = Vector2(x, 112.0)
\t\t\tsprite.scale = Vector2.ONE * min(48.0 / max(texture.get_width(), 1), 48.0 / max(texture.get_height(), 1))
\t\t\tadd_child(sprite)
\t\t\tx += 58.0
`;
};

